import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';

await mkdir('.tmp', { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1200 } });
const errors = [], modelRequests = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', request => { if (/huggingface|\.onnx/.test(request.url())) modelRequests.push(request.url()); });
const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
const images = () => page.locator('.pair canvas').evaluateAll(cs => cs.map(c => c.toDataURL()));
const footprint = () => page.locator('.rotation-outline polygon').getAttribute('points');
try {
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173');
  await page.getByLabel('Choose a photograph').setInputFiles('samples/IMG20240105123302.jpg');
  await page.getByRole('status').filter({ hasText: 'Photo ready' }).waitFor();
  assert.equal(await page.getByRole('checkbox', { name: 'Camera rotation', exact: true }).isChecked(), true);
  assert.equal(await page.getByRole('checkbox', { name: 'Depth enhancement', exact: true }).isChecked(), true);
  assert.equal(await page.getByLabel('Comparison baseline').count(), 0);
  await page.getByRole('checkbox', { name: 'Depth enhancement', exact: true }).uncheck();
  // Use known calibration regardless of the sample's EXIF.
  await page.getByLabel('Source focal length').fill('24');
  await page.getByLabel('Target focal length').fill('50');
  await settle();
  let pair = await images();
  assert.equal(pair[0], pair[1], 'Centered rotation must equal crop');
  assert.equal(await page.getByRole('button', { name: '↓ Rotation PNG' }).isEnabled(), true);
  const preview = page.getByRole('group', { name: 'Position crop', exact: true });
  const bounds = await preview.boundingBox();
  await preview.click({ position: { x: bounds.width * .97, y: bounds.height * .8 } });
  await settle();
  pair = await images();
  assert.equal(pair[0], pair[1], 'Baseline follows rotation with depth off');
  const points = (await footprint()).split(' ').map(pair => pair.split(',').map(Number));
  assert.equal(points.length, 4);
  for (const p of points) for (const n of p) assert.ok(n >= -1e-7 && n <= 100 + 1e-7);
  const beforeKey = await footprint();
  await preview.press('ArrowLeft'); await settle();
  assert.notEqual(await footprint(), beforeKey);
  const beforeDrag = await footprint();
  const cropBox = await page.locator('.crop-baseline').evaluate(el => {
    const bounds = el.parentElement.getBoundingClientRect();
    return { x: bounds.x + parseFloat(el.style.left) / 100 * bounds.width, y: bounds.y + parseFloat(el.style.top) / 100 * bounds.height, width: parseFloat(el.style.width) / 100 * bounds.width, height: parseFloat(el.style.height) / 100 * bounds.height };
  });
  await page.mouse.move(cropBox.x + cropBox.width / 2, cropBox.y + cropBox.height / 2);
  await page.mouse.down();
  await page.mouse.move(cropBox.x + cropBox.width / 2 - 40, cropBox.y + cropBox.height / 2 - 20, { steps: 4 });
  await page.mouse.up(); await settle();
  assert.notEqual(await footprint(), beforeDrag);
  await page.locator('.original-preview').screenshot({ path: '.tmp/rotation-original.png' });
  await page.locator('.pair').screenshot({ path: '.tmp/rotation-comparison.png' });
  await page.getByRole('button', { name: 'Compare without labels' }).click();
  await page.getByRole('button', { name: 'Prefer A', exact: true }).click();
  await page.getByRole('button', { name: 'Reveal labels' }).click();
  await page.getByText('Preference recorded in recipe.').waitFor();
  let downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: '↓ Edit recipe' }).click();
  await (await downloading).saveAs('.tmp/rotation-recipe.json');
  const recipe = JSON.parse(await readFile('.tmp/rotation-recipe.json', 'utf8'));
  assert.equal(recipe.renderer, 'fixed-center-rotation-v1');
  assert.equal(recipe.depth, null);
  assert.deepEqual(recipe.camera.translation, [0, 0, 0]);
  assert.ok(Math.abs(recipe.camera.yawDegrees) > 1);
  assert.equal(recipe.settings.target, 50);
  downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: '↓ Rotation PNG' }).click();
  await (await downloading).saveAs('.tmp/rotation-export.png');
  const png = await readFile('.tmp/rotation-export.png');
  assert.equal(png.subarray(1,4).toString(), 'PNG');
  assert.equal(png.readUInt32BE(16), recipe.workingSize[0]);
  assert.equal(png.readUInt32BE(20), recipe.workingSize[1]);
  await page.getByLabel('Target focal length').fill('24');
  await preview.click({ position: { x: 5, y: 5 } }); await settle();
  pair = await images(); assert.equal(pair[0], pair[1]);
  await page.getByRole('checkbox', { name: 'Camera rotation', exact: true }).uncheck();
  await page.getByRole('checkbox', { name: 'Depth enhancement', exact: true }).check(); await settle();
  assert.equal(await page.getByRole('button', { name: 'Estimate depth on this device' }).isEnabled(), true);
  assert.equal(await page.getByRole('button', { name: '↓ Enhanced PNG' }).isDisabled(), true);
  pair = await images(); assert.equal(pair[0], pair[1]);
  await page.getByRole('checkbox', { name: 'Depth enhancement', exact: true }).uncheck();
  await page.getByRole('checkbox', { name: 'Camera rotation', exact: true }).check();
  await page.getByLabel('Target focal length').fill('50');
  await page.setViewportSize({ width: 390, height: 844 }); await settle();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: '.tmp/rotation-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  assert.deepEqual(modelRequests, []);
  console.log('PASS: depth enabled by default, automatic rotation baseline, bounded footprint, pointer/keyboard movement, blind vote, PNG/recipe export, depth mode, and mobile layout; no model requests.');
} finally { await browser.close(); }
